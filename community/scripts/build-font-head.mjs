#!/usr/bin/env node
/**
 * Write theme/head.html: Pretendard's @font-face rules, pointed at the files
 * scripts/fetch-fonts.sh copies into Answer's branding upload folder.
 *
 * The rules go inline in Answer's custom head because Answer serves uploaded
 * .css files as image/css (with nosniff), so a <link> to them is refused, and
 * the 92 rules do not fit in the 64 KB custom CSS next to the theme.
 *
 *   node community/scripts/build-font-head.mjs <answer data>/uploads/branding/fonts/pretendard/pretendard.css
 *
 * Only needed again when the Pretendard version in fetch-fonts.sh changes.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const input = process.argv[2];
if (!input) {
  console.error('usage: build-font-head.mjs <path to pretendard.css>');
  process.exit(1);
}

const css = await readFile(input, 'utf8');
const rules = [...css.matchAll(/url\(\.\/woff2-dynamic-subset\/([\w.]+\.woff2)\) format\('woff2-variations'\);\s*unicode-range: ([^;]+);/g)];
if (rules.length === 0) throw new Error('no @font-face rules found');

const lines = rules.map(
  ([, file, range]) =>
    `@font-face{font-family:'Pretendard Variable';font-style:normal;font-display:swap;font-weight:45 920;` +
    `src:url(/uploads/branding/fonts/pretendard/woff2-dynamic-subset/${file}) format('woff2-variations');` +
    `unicode-range:${range.replace(/\s+/g, '')}}`,
);

const out = [
  '<style id="sc-fonts">',
  '/* Pretendard (c) 2021 Kil Hyung-jin, SIL Open Font License 1.1. Generated by scripts/build-font-head.mjs. */',
  ...lines,
  '</style>',
  '',
].join('\n');

const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'theme', 'head.html');
await writeFile(target, out);
console.log(`wrote ${rules.length} rules, ${out.length} characters, to ${target}`);
