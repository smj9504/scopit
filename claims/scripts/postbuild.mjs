#!/usr/bin/env node
/**
 * Runs after `astro build`:
 *   1. sitemap.xml — every page that is indexable (no robots noindex), using
 *      each page's own canonical URL and modified date.
 *   2. robots.txt  — points at the sitemap; keeps /admin and /api out.
 *   3. _headers    — Cloudflare Pages security headers, including a strict
 *      Content-Security-Policy (adds Plausible only when it is configured).
 *   4. Guards      — fails on inline executable scripts (the CSP would block
 *      them) and on dev-fixture data in a production build.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import { loadBuildEnv } from './build-env.mjs';

loadBuildEnv();

const DIST = new URL('../dist/', import.meta.url).pathname;
const errors = [];

async function walk(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(full)));
    else out.push(full);
  }
  return out;
}

const files = await walk(DIST);
const htmlFiles = files.filter((f) => f.endsWith('.html'));

function attr(html, re) {
  const m = html.match(re);
  return m ? m[1] : null;
}

/* ---------- Collect pages ---------- */
const pages = [];
for (const file of htmlFiles) {
  const html = await readFile(file, 'utf8');
  const rel = relative(DIST, file).split(sep).join('/');
  const canonical = attr(html, /<link rel="canonical" href="([^"]+)"/);
  const robots = attr(html, /<meta name="robots" content="([^"]+)"/) || '';
  const modified = attr(html, /<meta property="article:modified_time" content="([^"]+)"/);
  pages.push({ rel, html, canonical, noindex: /noindex/.test(robots), modified });

  // Guard: inline scripts other than JSON-LD/data blocks.
  const scripts = html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/g);
  for (const [, attrs, body] of scripts) {
    const isData = /type="application\/ld\+json"/.test(attrs) || /type="application\/json"/.test(attrs);
    if (!/\ssrc=/.test(attrs) && !isData && body.trim()) {
      errors.push(`${rel}: inline <script> found; the CSP blocks it. Move it to a module script.`);
    }
  }
}

if (process.env.CLAIMS_ENV === 'production') {
  for (const p of pages) {
    if (/DEV FIXTURE/i.test(p.html)) errors.push(`${p.rel}: dev fixture data in a production build.`);
    if (p.html.includes('1x00000000000000000000AA')) {
      errors.push(`${p.rel}: Turnstile test site key in a production build. Set PUBLIC_TURNSTILE_SITE_KEY.`);
    }
  }
}

/* ---------- Sitemap ---------- */
const home = pages.find((p) => p.rel === 'index.html');
if (!home?.canonical) errors.push('index.html has no canonical URL; cannot build sitemap.');
const siteRoot = home?.canonical ?? 'https://claims.scopit.work/';
const today = new Date().toISOString().slice(0, 10);

const urls = pages
  .filter((p) => p.canonical && !p.noindex && p.rel !== '404.html')
  .sort((a, b) => a.canonical.localeCompare(b.canonical))
  .map((p) => `  <url><loc>${p.canonical}</loc><lastmod>${p.modified || today}</lastmod></url>`);

await writeFile(
  join(DIST, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.join('\n')}\n</urlset>\n`,
);

/* ---------- robots.txt ---------- */
const basePath = new URL(siteRoot).pathname.replace(/\/$/, '');
await writeFile(
  join(DIST, 'robots.txt'),
  [
    'User-agent: *',
    `Disallow: ${basePath}/admin`,
    `Disallow: ${basePath}/api/`,
    `Disallow: ${basePath}/find-an-adjuster/inquiry/`,
    '',
    `Sitemap: ${siteRoot}sitemap.xml`,
    '',
  ].join('\n'),
);

/* ---------- _headers ---------- */
const plausibleSrc = process.env.PUBLIC_PLAUSIBLE_DOMAIN
  ? new URL(process.env.PUBLIC_PLAUSIBLE_SRC || 'https://plausible.io/js/script.js').origin
  : '';
const csp = [
  "default-src 'self'",
  `script-src 'self' https://challenges.cloudflare.com${plausibleSrc ? ` ${plausibleSrc}` : ''}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data:",
  "font-src 'self'",
  `connect-src 'self'${plausibleSrc ? ` ${plausibleSrc}` : ''}`,
  'frame-src https://challenges.cloudflare.com',
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  'upgrade-insecure-requests',
].join('; ');

await writeFile(
  join(DIST, '_headers'),
  `# Generated by scripts/postbuild.mjs. Static assets only; Functions set their own headers.
/*
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()
  X-Frame-Options: DENY
  Strict-Transport-Security: max-age=31536000; includeSubDomains

/fonts/*
  Cache-Control: public, max-age=31536000, immutable

/_astro/*
  Cache-Control: public, max-age=31536000, immutable

/og/*
  Cache-Control: public, max-age=86400
`,
);

if (errors.length) {
  console.error(`postbuild: ${errors.length} problem(s):\n- ${errors.join('\n- ')}`);
  process.exit(1);
}
console.log(`postbuild: sitemap (${urls.length} URLs), robots.txt, _headers written.`);
